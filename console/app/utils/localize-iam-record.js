/**
 * Display text for system IAM policies and roles ("FLB Managed").
 *
 * Their descriptions are seeded in English by the API (`*Auth/Schemas/*.php` and the
 * `CreatePermissions` command) and stored in the database, so they are translated on the frontend
 * by the fixed system name + service, under `iam.ui.system-policies.*` / `iam.ui.system-roles.*`.
 * Records created by an organization (company_uuid set) are always shown as typed by the user.
 */
const slugify = (value) =>
    String(value ?? '')
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-|-$/g, '');

/** Generated by CreatePermissions for every schema: "<Name>FullAccess" / "<Name>ReadOnly". */
const GENERATED_POLICY_DESCRIPTIONS = [
    { suffix: 'FullAccess', pattern: /^Policy for full access to (.+)\.$/, key: 'full-access' },
    { suffix: 'ReadOnly', pattern: /^Policy for read-only access to (.+)\.$/, key: 'read-only' },
];

export function isSystemIamRecord(record) {
    return !record?.company_uuid;
}

export function localizeIamDescription(intl, record, kind = 'policy') {
    const description = record?.description;
    if (!intl || !record || !isSystemIamRecord(record) || typeof description !== 'string') {
        return description;
    }

    const base = kind === 'role' ? 'iam.ui.system-roles' : 'iam.ui.system-policies';
    const service = slugify(record.service) || 'core';
    const name = slugify(record.name);
    const candidates = [`${base}.${service}.${name}`, `${base}.any.${name}`];

    for (const key of candidates) {
        if (intl.exists(key)) {
            return intl.t(key);
        }
    }

    if (kind === 'policy') {
        for (const { suffix, pattern, key } of GENERATED_POLICY_DESCRIPTIONS) {
            const match = description.match(pattern);
            if (match && String(record.name ?? '').endsWith(suffix) && intl.exists(`${base}.generated.${key}`)) {
                return intl.t(`${base}.generated.${key}`, { name: match[1] });
            }
        }
    }

    return description;
}

/** "FLB Managed" / "Organization Managed" (computed by the API from company_uuid). */
export function localizeIamType(intl, record) {
    const type = record?.type;
    if (!intl || typeof type !== 'string') {
        return type;
    }

    const key = { 'FLB Managed': 'iam.ui.scheme-types.flb-managed', 'Fleetbase Managed': 'iam.ui.scheme-types.flb-managed', 'Organization Managed': 'iam.ui.scheme-types.org-managed' }[type];
    return key && intl.exists(key) ? intl.t(key) : type;
}
