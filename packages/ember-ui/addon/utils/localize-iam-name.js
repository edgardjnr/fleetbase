/**
 * Display name for system IAM roles and policies ("FLB Managed").
 *
 * System roles/policies are seeded in English by the API (`*Auth/Schemas/*.php` and the
 * `CreatePermissions` command) and their names are identifiers used by the backend
 * (e.g. `assignSingleRole('Administrator')`), so they are never changed — only the text shown
 * is translated, under `iam.ui.system-role-names.*` / `iam.ui.system-policy-names.*`.
 * Records created by an organization (company_uuid set) are always shown as typed by the user.
 * Unknown names fall back to the original value.
 */
const slugify = (value) =>
    String(value ?? '')
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-|-$/g, '');

/** Generated by CreatePermissions for every schema: "<PolicyName>FullAccess" / "<PolicyName>ReadOnly". */
const GENERATED_POLICY_SUFFIXES = [
    { suffix: 'FullAccess', key: 'full-access' },
    { suffix: 'ReadOnly', key: 'read-only' },
];

export function localizeIamName(intl, name, kind = 'role', record = null) {
    if (!intl || typeof name !== 'string' || !name) {
        return name;
    }

    // organization-created records keep the name typed by the user (plain API payloads carry "type")
    if (record && (record.company_uuid || record.type === 'Organization Managed')) {
        return name;
    }

    try {
        const base = kind === 'policy' ? 'iam.ui.system-policy-names' : 'iam.ui.system-role-names';
        const key = `${base}.${slugify(name)}`;
        if (intl.exists(key)) {
            return intl.t(key);
        }

        if (kind === 'policy') {
            for (const { suffix, key: generatedKey } of GENERATED_POLICY_SUFFIXES) {
                if (name.length > suffix.length && name.endsWith(suffix) && intl.exists(`${base}.generated.${generatedKey}`)) {
                    const prefix = name.slice(0, -suffix.length);
                    const serviceKey = `${base}.services.${slugify(prefix)}`;
                    const service = intl.exists(serviceKey) ? intl.t(serviceKey) : prefix;
                    return intl.t(`${base}.generated.${generatedKey}`, { name: service });
                }
            }
        }
    } catch (error) {
        return name;
    }

    return name;
}

/** "FLB Managed" / "Fleetbase Managed" / "Organization Managed" (computed by the API from company_uuid). */
export function localizeIamType(intl, type) {
    if (!intl || typeof type !== 'string') {
        return type;
    }

    const key = { 'FLB Managed': 'iam.ui.scheme-types.flb-managed', 'Fleetbase Managed': 'iam.ui.scheme-types.flb-managed', 'Organization Managed': 'iam.ui.scheme-types.org-managed' }[type];
    return key && intl.exists(key) ? intl.t(key) : type;
}

export default localizeIamName;
